export const enhancedMonarchSqlLanguage: any = {
  defaultToken: '',
  tokenPostfix: '.sql',
  ignoreCase: true,
  brackets: [
    { open: '[', close: ']', token: 'delimiter.square' },
    { open: '(', close: ')', token: 'delimiter.parenthesis' },
  ],
  keywords: MYSQL_KEYWORDS,
  operators: MYSQL_OPERATORS,
  builtinFunctions: MYSQL_BUILTIN_FUNCTIONS,
  builtinVariables: MYSQL_BUILTIN_VARIABLES,
  pseudoColumns: ['$ACTION', '$IDENTITY', '$ROWGUID'],
  tokenizer: {
    root: [
      { include: '@comments' },
      { include: '@whitespace' },
      { include: '@pseudoColumns' },
      { include: '@numbers' },
      { include: '@strings' },
      { include: '@complexIdentifiers' },
      { include: '@scopes' },
      [/[;,.]/, 'delimiter'],
      [/[()]/, '@brackets'],
      [
        /[\w@#$]+/,
        {
          cases: {
            '@operators': 'operator',
            '@builtinVariables': 'predefined',
            '@builtinFunctions': 'predefined',
            '@keywords': 'keyword',
            '@default': 'identifier',
          },
        },
      ],
      [/[<>=!%&+\-*/|~^]/, 'operator'],
    ],
    whitespace: [[/\s+/, 'white']],
    comments: [
      [/--+.*/, 'comment'],
      [/#+.*/, 'comment'], // Comentários de linha estilo MySQL com #
      [/\/\*/, { token: 'comment.quote', next: '@comment' }],
    ],
    comment: [
      [/[^/*]+/, 'comment'],
      [/\*\//, { token: 'comment.quote', next: '@pop' }],
      [/[\/*]/, 'comment'],
    ],
    pseudoColumns: [
      [
        /[$][A-Za-z_][\w@#$]*/,
        {
          cases: {
            '@pseudoColumns': 'predefined',
            '@default': 'identifier',
          },
        },
      ],
    ],
    numbers: [
      [/0[xX][0-9a-fA-F]+/, 'number'],
      [/[$][+-]*\d*(\.\d+)?/, 'number'],
      [/((\d+(\.\d*)?)|(\.\d+))([eE][\-+]?\d+)?/, 'number'],
    ],
    strings: [
      [/N'/, { token: 'string', next: '@string' }],
      [/'/, { token: 'string', next: '@string' }],
    ],
    string: [
      [/[^']+/, 'string'],
      [/''/, 'string'],
      [/'/, { token: 'string', next: '@pop' }],
    ],
    complexIdentifiers: [
      [/\[/, { token: 'identifier.quote', next: '@bracketedIdentifier' }],
      [/`/, { token: 'identifier.quote', next: '@quotedIdentifier' }],
      [/"/, { token: 'identifier.quote', next: '@quotedIdentifier' }],
    ],
    bracketedIdentifier: [
      [/[^\]]+/, 'identifier'],
      [/\]\]/, 'identifier'],
      [/\]/, { token: 'identifier.quote', next: '@pop' }],
    ],
    quotedIdentifier: [
      [/[^`"]+/, 'identifier'],
      [/``|""/, 'identifier'],
      [/[`"]/, { token: 'identifier.quote', next: '@pop' }],
    ],
    scopes: [],
  },
};

/**
 * Registra o Monarch Tokenizer enriquecido para 'sql' e 'mysql' no Monaco Editor.
 * Garante que funções como NOW(), CEIL(), CURDATE(), IFNULL(), DATEDIFF() fiquem
 * perfeitamente destacadas com o token 'predefined' (cor laranja vibrante do tema).
 */
export function registerEnhancedSqlLanguage(monaco: any) {
  if (!monaco || !monaco.languages || typeof monaco.languages.setMonarchTokensProvider !== 'function') return;
  try {
    monaco.languages.setMonarchTokensProvider('sql', enhancedMonarchSqlLanguage);
    monaco.languages.setMonarchTokensProvider('mysql', enhancedMonarchSqlLanguage);
  } catch (err) {
    console.warn('Falha ao registrar tokenizer SQL/MySQL customizado no Monaco:', err);
  }
}
