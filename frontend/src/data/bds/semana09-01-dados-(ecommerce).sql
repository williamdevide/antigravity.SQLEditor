CREATE DATABASE db_ecommerce IF NOT EXISTS;
USE db_ecommerce;

DROP TABLE IF EXISTS tb_itens_pedido;
DROP TABLE IF EXISTS tb_pedidos;
DROP TABLE IF EXISTS tb_produtos;
DROP TABLE IF EXISTS tb_clientes;
DROP TABLE IF EXISTS tb_clientes_antigos;

CREATE TABLE IF NOT EXISTS tb_clientes (
    id_cliente INTEGER PRIMARY KEY AUTOINCREMENT,
    nome_cliente VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    cidade VARCHAR(50) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    data_cadastro DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_clientes_antigos (
    id_cliente INTEGER PRIMARY KEY AUTOINCREMENT,
    nome_cliente VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    cidade VARCHAR(50) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    data_cadastro DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_produtos (
    id_produto INTEGER PRIMARY KEY AUTOINCREMENT,
    nome_produto VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    preco DECIMAL(10,2) NOT NULL,
    estoque INT NOT NULL
);

CREATE TABLE IF NOT EXISTS tb_pedidos (
    id_pedido INTEGER PRIMARY KEY AUTOINCREMENT,
    fk_cliente INTEGER NOT NULL,
    data_pedido DATE NOT NULL,
    valor_total DECIMAL(10,2) NOT NULL,
    forma_pagamento VARCHAR(30) NOT NULL,
    status_pedido VARCHAR(20) NOT NULL,
    FOREIGN KEY (fk_cliente) REFERENCES tb_clientes(id_cliente)
);

CREATE TABLE IF NOT EXISTS tb_itens_pedido (
    id_item INTEGER PRIMARY KEY AUTOINCREMENT,
    fk_pedido INTEGER NOT NULL,
    fk_produto INTEGER NOT NULL,
    quantidade INT NOT NULL,
    preco_unitario DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (fk_pedido) REFERENCES tb_pedidos(id_pedido),
    FOREIGN KEY (fk_produto) REFERENCES tb_produtos(id_produto)
);


